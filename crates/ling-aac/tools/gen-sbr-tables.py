#!/usr/bin/env python3
"""Regenerate src/sbr/tables.rs.

The values are the ISO/IEC 14496-3 SBR tables (QMF window, noise table,
Huffman tables, start-frequency offsets). They are read from a reference
transcription of those tables; pass the directory that holds FFmpeg's
libavcodec/{aacsbrdata.h,sbrdsp_template.c,aac/aacdec_tab.c} (data only).
Usage: gen-sbr-tables.py <dir> <out.rs>
"""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
rd = lambda f: open(f"{src}/{f}").read()
def block(s, name):
    i = s.index(name); j = s.index('{', i); k = s.index('};', j); return s[j + 1:k]
q31 = lambda s: [(-1.0 if neg else 1.0) * float(x) for neg, x in re.findall(r'(-?)\s*Q31\(\s*([-0-9.]+)f\)', s)]
d = rd('aacsbrdata.h')
us = q31(block(d, 'sbr_qmf_window_us')); assert len(us) == 640
off = [[int(x) for x in re.findall(r'-?\d+', r)] for r in re.findall(r'\{([^{}]*)\}', block(d, 'sbr_offset[6][16]'))]
noise = q31(block(rd('sbrdsp_template.c'), 'ff_sbr_noise_table'))[:1024]
pairs = [(int(a), int(b)) for a, b in re.findall(r'\{\s*(\d+),\s*(\d+)\s*\}', block(rd('aacdec_tab.c'), 'sbr_huffman_tab[][2]'))]
nbc = [121, 121, 49, 49, 63, 63, 25, 25, 63, 25]
offs = [-60, -60, -24, -24, -31, -31, -12, -12, -31, -12]
names = ['T_ENV_1_5DB', 'F_ENV_1_5DB', 'T_ENV_BAL_1_5DB', 'F_ENV_BAL_1_5DB', 'T_ENV_3_0DB', 'F_ENV_3_0DB',
         'T_ENV_BAL_3_0DB', 'F_ENV_BAL_3_0DB', 'T_NOISE_3_0DB', 'T_NOISE_BAL_3_0DB']
assert len(pairs) == sum(nbc)
o = ["""//! SBR constant tables from ISO/IEC 14496-3 (QMF window c(n) Table 4.A.87,
//! noise table V(k) Table 4.A.90, Huffman tables 4.A.78-4.A.86, start
//! frequency offsets 4.6.18.3.2). Generated by tools/gen-sbr-tables.py; the
//! Huffman tables are (symbol, length) pairs in canonical code order (codes
//! are assigned consecutively) plus the symbol offset.

#![allow(clippy::excessive_precision)]
#![allow(clippy::approx_constant)]
""", "/// QMF prototype window c(n), n = 0..639.", "pub static QMF_WINDOW: [f32; 640] = ["]
o += ["    " + ", ".join("%.10f" % v for v in us[i:i + 4]) + "," for i in range(0, 640, 4)]
o += ["];\n", "/// Start frequency offsets (bs_start_freq) per output-rate class.", "pub static START_OFFSET: [[i8; 16]; 6] = ["]
o += ["    [" + ", ".join(map(str, r)) + "]," for r in off]
o += ["];\n", "/// Noise table V(k), k = 0..511: (re, im).", "pub static NOISE_TABLE: [[f32; 2]; 512] = ["]
o += ["    [%.14f, %.14f], [%.14f, %.14f]," % tuple(noise[i:i + 4]) for i in range(0, 1024, 4)]
o += ["];\n"]
p = 0
for n, c, of in zip(names, nbc, offs):
    seg = pairs[p:p + c]; p += c
    o.append("pub static %s: ([(u8, u8); %d], i8) = ([" % (n, c))
    o += ["    " + " ".join("(%d, %d)," % x for x in seg[i:i + 8]) for i in range(0, c, 8)]
    o.append("], %d);\n" % of)
open(dst, 'w', newline='\n').write("\n".join(o))
