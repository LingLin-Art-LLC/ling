#!/usr/bin/env python3
"""Regenerate ling-fxcore/src/dsp/*.rs from ling-daw's effect sources.

LingStationX's effects live in ling-daw (a std crate). The kernel's DAW
(ling-kernel/src/lingdaw.rs) runs the very same DSP through this no_std copy:
the files are copied verbatim except for

  * a prelude import (Vec/Box/String/format!/vec! + the libm-backed float
    methods) after the module's `//!` docs,
  * `std::` -> `core::`,
  * `ling_music::decode::load` -> `crate::host::load_audio` (the kernel hooks it),
  * the `#[cfg(test)]` module at the end dropped (they use std / ling-daw).

Run after changing an effect in ling-daw:  python crates/ling-fxcore/tools/gen.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
SRC = os.path.join(CRATE, "..", "ling-daw", "src", "dsp")
DST = os.path.join(CRATE, "src", "dsp")

FILES = ["fx", "bassfx", "edmfx", "cinefx", "vox", "master", "warp", "articulator", "hypergrowl", "vocoder", "guitar"]

PRELUDE = "#[allow(unused_imports)]\nuse crate::prelude::*;\n"


def convert(text: str) -> str:
    text = text.replace("\r\n", "\n")
    lines = text.split("\n")
    # drop the trailing test module(s)
    for i, l in enumerate(lines):
        if l.startswith("#[cfg(test)]"):
            lines = lines[:i]
            break
    # prelude after the inner doc comment / attributes at the top
    j = 0
    while j < len(lines) and (lines[j].startswith("//!") or lines[j].startswith("#![")):
        j += 1
    lines.insert(j, PRELUDE.rstrip("\n"))
    out = "\n".join(lines).rstrip() + "\n"
    out = re.sub(r"(?<![\w:])std::collections::", "alloc::collections::", out)
    out = re.sub(r"(?<![\w:])std::", "core::", out)
    out = out.replace("ling_music::decode::load(", "crate::host::load_audio(")
    return "// GENERATED by crates/ling-fxcore/tools/gen.py from ling-daw/src/dsp -- edit there, then regenerate.\n" + out


def main():
    os.makedirs(DST, exist_ok=True)
    jobs = [(os.path.join(SRC, f + ".rs"), os.path.join(DST, f + ".rs")) for f in FILES]
    # the piano roll's per-note expression (pitch gestures, pressure, timbre curves): pure data edits on notes
    jobs.append((os.path.join(SRC, "..", "gesture.rs"), os.path.join(CRATE, "src", "gesture.rs")))
    for src_p, dst_p in jobs:
        with open(src_p, encoding="utf-8") as fh:
            src = fh.read()
        with open(dst_p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(convert(src))
        print("wrote", os.path.relpath(dst_p, CRATE))


if __name__ == "__main__":
    main()
