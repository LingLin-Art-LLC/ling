import re,sys
src=open('h264_cabac.c').read()
def arr(name):
    i=src.index(name); j=src.index('};',i)
    body=src[i:j]
    body=re.sub(r'/\*.*?\*/','',body,flags=re.S)
    body=body[body.index('{')+1:]
    return [(int(a),int(b)) for a,b in re.findall(r'\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}',body)]
I=arr('cabac_context_init_I[1024][2]')
PB=arr('cabac_context_init_PB[3][1024][2]')
assert len(I)==1024 and len(PB)==3072,(len(I),len(PB))
N=460
out=[]
out.append('// CABAC context initialisation (m, n) pairs, ctxIdx 0..459 (ITU-T H.264 Tables 9-12..9-33).')
out.append('// Generated by tools/gen_tables.py; do not edit.')
def emit(name,lst):
    out.append('pub static %s: [[i8; 2]; %d] = ['%(name,N))
    for k in range(0,N,8):
        out.append('    '+' '.join('[%d, %d],'%p for p in lst[k:k+8]))
    out.append('];')
emit('CABAC_INIT_I',I[:N])
for t in range(3): emit('CABAC_INIT_PB%d'%t,PB[t*1024:t*1024+N])
c=open('cabac.c').read()
i=c.index('// LPS range'); j=c.index('// mlps state')
v=[int(x) for x in re.findall(r'-?\d+',c[i:j])]
assert len(v)==512
rt=[[v[q*128+2*s]&255 for q in range(4)] for s in range(64)]
out.append('pub static RANGE_LPS: [[u8; 4]; 64] = [')
for s in range(64): out.append('    [%d, %d, %d, %d],'%tuple(rt[s]))
out.append('];')
k=c.index('// mlps state'); m=[int(x) for x in re.findall(r'-?\d+',c[k:k+4000])][:256]
lps=[]
for s in range(64):
    # mlps[127 - (2s+0)] gives new state for LPS with mps=0 ... value = 2*newstate + newmps
    val=m[127-(2*s)]
    lps.append(val>>1)
mps=[m[128+2*s]>>1 for s in range(64)]
out.append('pub static TRANS_LPS: [u8; 64] = [%s];'%', '.join(map(str,lps)))
out.append('pub static TRANS_MPS: [u8; 64] = [%s];'%', '.join(map(str,mps)))
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
print(lps);print(mps)
